int64_t tn_cuda_ultra_batch_gemm(
    int64_t x_h, int64_t w_h, int64_t w_off, int64_t y_h, int64_t b_h, int64_t b_off,
    int64_t batch, int64_t out_dim, int64_t in_dim, int64_t quant_mode, int64_t add_res, int64_t has_bias
) {
    CUdeviceptr px = tn_cuda_buf_dptr(x_h);
    CUdeviceptr pw = tn_cuda_buf_dptr(w_h) + (uint64_t)w_off;
    CUdeviceptr py = tn_cuda_buf_dptr(y_h);
    CUdeviceptr pb = has_bias ? (tn_cuda_buf_dptr(b_h) + (uint64_t)b_off) : py;
    uint32_t ub = (uint32_t)batch, un = (uint32_t)out_dim, uk = (uint32_t)in_dim;
    uint32_t ar = (uint32_t)add_res, hb = (uint32_t)has_bias;
    if (quant_mode == 2 && ub <= 8u) {
        void* params[9] = { &px, &pw, &py, &pb, &ub, &un, &uk, &ar, &hb };
        return tn_cuda_launch_raw(k_batch_gemm_q4_b4, (un + 3u) / 4u, 1, 1, 128, 1, 1, 0, params);
    }
    if (quant_mode == 2 && ub <= 32u) {
        /* Roofline Adaptive Split-K for Ping-Pong BN=32 x BK=32 W4A16 MMA (saturates all 128 RTX 4090 SMs!) */
        uint32_t sk = 1u;
        if (un <= 3072u && uk >= 8192u && (ub * un) <= (32u * 16384u)) sk = 8u;
        else if (un <= 3072u && uk >= 2048u && (ub * un) <= (32u * 16384u)) sk = 4u;
        CUdeviceptr psk = g_sk_scratch_dptr;
        void* params[11] = { &px, &pw, &py, &psk, &pb, &ub, &un, &uk, &ar, &hb, &sk };
        if (!tn_cuda_launch_raw(k_batch_gemm_q4_mma, (un + 31u) / 32u, sk, 1, 128, 1, 1, 0, params)) return 0;
        if (sk > 1u) {
            void* fps[7] = { &psk, &py, &pb, &ub, &un, &ar, &hb };
            return tn_cuda_launch_raw(k_sk_finish, (ub * un + 255u) / 256u, 1, 1, 256, 1, 1, 0, fps);
        }
        return 1;
    }
    return tn_cuda_ultra_mm(x_h, w_h, w_off, y_h, batch, out_dim, in_dim, quant_mode, add_res);
}

