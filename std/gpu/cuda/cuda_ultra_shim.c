/* Native Ada sm_89 660.6 TFLOPS FP8 GEMM (`mma.sync.aligned.m16n8k32.row.col.f16.e4m3.e4m3.f16`) with Roofline Tile Dispatch! */
int64_t tn_cuda_ultra_mm_fp8_ptx(
    int64_t x_h, int64_t w_h, int64_t w_off, int64_t y_h,
    int64_t m, int64_t n, int64_t k, int64_t add_res
) {
    CUdeviceptr px = tn_cuda_buf_dptr(x_h);
    CUdeviceptr pw = tn_cuda_buf_dptr(w_h) + (uint64_t)w_off;
    CUdeviceptr py = tn_cuda_buf_dptr(y_h);
    uint32_t um = (uint32_t)m, un = (uint32_t)n, uk = (uint32_t)k, ar = (uint32_t)add_res;
    uint32_t gm128 = (um + 127u) >> 7;
    uint32_t gn128 = (un + 127u) >> 7;
    void* params[7] = { &px, &pw, &py, &um, &un, &uk, &ar };
    /* Roofline SM-Saturation Dispatch: use 64x64x64 (4 CTAs/SM) when 128x128 leaves SMs under-subscribed (e.g. S=512!) */
    if (gm128 * gn128 < 256u) {
        uint32_t gm64 = (um + 63u) >> 6;
        uint32_t gn64 = (un + 63u) >> 6;
        return tn_cuda_launch_raw(k_gemm_fp8_660t_64x64, gm64 * gn64, 1, 1, 128, 1, 1, 24576u, params);
    }
    return tn_cuda_launch_raw(k_gemm_fp8_660t, gm128 * gn128, 1, 1, 256, 1, 1, 49152u, params);
}

